"""Generate scripts/game_data.gd from the server's runtime/cards.go.

The server's card table is the single source of truth (it is the real Splendor
deck, guarded by runtime/deck_test.go). Run this after any change to it:

    python tools/gen_cards.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.normpath(os.path.join(HERE, "..", "..", "runtime", "cards.go"))
OUT = os.path.normpath(os.path.join(HERE, "..", "scripts", "game_data.gd"))

# server element -> client colour key (coin / pip / silhouette art)
COLOR = {"ELight": "white", "EWater": "blue", "ENature": "green", "EFire": "red", "EShadow": "black"}
ORDER = ["white", "blue", "green", "red", "black"]  # Splendor's cost order


def costs(body):
    got = {COLOR[k]: int(v) for k, v in re.findall(r"(E\w+): (\d+)", body)}
    return [[c, got[c]] for c in ORDER if c in got]


def main():
    src = open(SRC, encoding="utf-8").read()
    cards = []
    for m in re.finditer(r'\{ID: "([^"]+)", Name: "([^"]+)", Tier: (\d), Power: (\d), '
                         r'Affinity: (\w+), HireCost: Cost\{([^}]*)\}\}', src):
        cid, name, tier, power, aff, body = m.groups()
        cards.append((cid, name, int(tier), int(power), COLOR[aff], costs(body)))
    arts = []
    for m in re.finditer(r'\{ID: "([^"]+)", Name: "([^"]+)", Requirement: Cost\{([^}]*)\}\}', src):
        aid, name, body = m.groups()
        req = costs(body)
        arts.append((aid, name, [c for c, _ in req], req[0][1]))
    assert len(cards) == 90, len(cards)
    assert len(arts) == 10, len(arts)

    lines = [
        "# Generated by tools/gen_cards.py from runtime/cards.go - do not edit.",
        "# The real Splendor deck: 90 characters and 10 artifacts (nobles).",
        "class_name GameData",
        "extends RefCounted",
        "",
        "const CARDS := {",
    ]
    for cid, name, tier, power, el, cost in cards:
        cs = ", ".join('["%s", %d]' % (c, n) for c, n in cost)
        lines.append('\t"%s": {"id": "%s", "name": "%s", "tier": %d, "points": %d, "element": "%s", '
                     '"costs": [%s], "portrait": "%s"},' % (cid, cid, name.replace('"', '\\"'), tier, power, el, cs, cid))
    lines += ["}", "", "## Each needs `need` characters of every colour in `reqs`; worth 3 prestige.", "const ARTIFACTS := ["]
    for aid, name, reqs, need in arts:
        lines.append('\t{"id": "%s", "name": "%s", "reqs": [%s], "need": %d},'
                     % (aid, name, ", ".join('"%s"' % r for r in reqs), need))
    lines += ["]", ""]
    open(OUT, "w", encoding="utf-8").write("\n".join(lines))
    print("wrote", OUT, "-", len(cards), "cards,", len(arts), "artifacts")


if __name__ == "__main__":
    main()
